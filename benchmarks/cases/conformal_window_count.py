r"""How many calibration windows a cumulative conformal band needs.

mlsynth's cumulative band (:func:`mlsynth.utils.conformal.block_error_paths`)
prices the total effect over an ``H``-period horizon by resampling an
out-of-sample error series into synthetic ``H``-period paths. A total over ``H``
periods is ``H`` times the mean error over those periods, so the term that sizes
it is a *level* -- and a level is observed once per calibration window, not once
per period. The calibration set for the dominant term therefore has size ``m``,
the number of windows, and not ``m * H``.

That is the constraint this case pins down. Everything a conformal band is
usually asked to worry about is granted here: the level and the fluctuation are
Gaussian, independent, stationary, and exchangeable across windows, and the
draw's own variance-components estimator is handed data generated by exactly the
model it assumes. The only quantity that varies is ``m``. Coverage still falls
well short of nominal at small ``m`` and climbs monotonically with it, which
locates the shortfall in the window count and rules out the exchangeability
failures that the time-series conformal literature usually blames.

The two variance constants are measured, not invented: they are the level and
within-window spreads of MAREX's blank-period discrepancy on a 211-market weekly
sales panel at ``T0 = 104``, ``Tb = 47``, ``H = 13``. The panel is proprietary and
is not shipped, so the case regenerates the same two-component structure from
them; the study scripts that measured them are under
``benchmarks/studies/cumulative_calibration/``.

Consequences for a user: an estimator whose calibration window supports three
sub-windows cannot deliver a nominal cumulative band no matter how clean its
errors are, and the fix is more windows or more units, not a better resampler.
"""
from __future__ import annotations

_H = 13
_ALPHA = 0.05
_SD_LEVEL = 0.01569        # spread of the per-window level, measured
_SD_WITHIN = 0.00986       # spread of the within-window block mean, measured
_M_GRID = (3, 8, 26)
_N_DRAWS = 1500
_N_SIM = 1000


def _coverage(m: int, n_draws: int, n_sim: int, seed: int) -> float:
    """Share of draws whose realised ``H``-period total falls inside the band.

    Each draw builds ``m`` calibration windows and one held-out window from the
    same law, hands the calibration windows to the library's own draw, and asks
    whether the held-out total is covered.
    """
    import numpy as np
    from mlsynth.utils.conformal import block_error_paths

    sd_e = _SD_WITHIN * np.sqrt(_H)      # per-period sd giving that block-mean sd
    rng = np.random.default_rng(seed)
    hit = 0
    for d in range(n_draws):
        level = rng.normal(0.0, _SD_LEVEL, m + 1)
        calibration = (level[:m, None] + rng.normal(0.0, sd_e, (m, _H))).ravel()
        held_out = float((level[m] + rng.normal(0.0, sd_e, _H)).sum())
        paths = block_error_paths(
            calibration, horizon=_H, block=0, n_sim=n_sim,
            rng=np.random.default_rng(seed * 100_003 + d), n_windows=m)
        half = float(np.quantile(np.abs(paths.sum(axis=1)), 1.0 - _ALPHA))
        hit += abs(held_out) <= half
    return hit / n_draws


def run() -> dict:
    out = {f"coverage_m{m}": _coverage(m, _N_DRAWS, _N_SIM, seed=17 + i)
           for i, m in enumerate(_M_GRID)}
    out["gain_m3_to_m26"] = out["coverage_m26"] - out["coverage_m3"]
    return out


