"""jackknife+ cross-validation: ridge ASCM intervals vs augsynth, Kansas.

Cross-validation (the reference is the **augsynth** R package, Ben-Michael,
Feller & Rothstein 2021, pinned at commit ``7a90ea48``). ``augsynth``'s
``inf_type = "jackknife+"`` resamples over *pre-treatment periods*: each is held
out in turn, the augmented control is refitted without it, and the interval is
built from how badly the refit predicts the period it never saw.

This case is deliberately narrow. ``ascm_kansas`` already pins the ridge ASCM
*point* estimate against a live augsynth run, exactly, on this same panel -- so
the fit is not a confound here and anything this case catches is the inference.

What is pinned, and why at these tolerances:

* the per-drop seam -- the held-out error and the refit's post-period path for
  each of the 89 dropped pre-periods. This is the quantity the interval is built
  from, and pinning it means a regression is localised to one refit rather than
  reported as "the interval moved";
* the assembled bounds under BOTH settings of ``conservative``. The two branches
  build from different rows of the jackknife distribution, so a case that
  exercised one would leave the other entirely unguarded;
* the bound on the post-period average -- the row augsynth prints as
  ``average_att`` -- which is the number a user actually quotes.

The tolerances differ between branches and the gap is itself the finding. The
base simplex fit under every refit is a constrained QP, solved here by mlsynth's
exact solver and in the reference by ``quadprog``/osqp; two exact solvers agree
to their own tolerances rather than bit-for-bit, so ~1e-7 is the floor for
anything downstream. Taking quantiles across 89 drops averages that difference
away and the default branch lands at ~4e-9. The conservative branch takes the
min and max over drops, deliberately selecting the most extreme refit -- where
the solver difference is largest -- and lands at ~1.8e-7. An interval built from
order statistics cannot be more reproducible than its worst-case term.

One finding worth recording, because the argument's name misleads. augsynth's
``conservative = TRUE`` is *not* uniformly wider: on this panel it is narrower in
16 of 17 periods. Its envelope over the per-drop predictions is wider, but it
widens by the :math:`1-\alpha` quantile of the absolute held-out errors where the
default reaches the :math:`1-\alpha/2` quantile of ``est + |err|``. With a
right-skewed error distribution -- here the maximum absolute error is 0.037
against a 95th percentile of 0.013 -- the default's deeper reach into that tail
dominates the envelope, and the "conservative" interval comes out tighter. This
is a property of the reference, faithfully reproduced, not a defect in the port,
and it is why this case pins the conservative branch's *construction* rather than
a width ordering.

Provenance: gold generated by ``benchmarks/reference/ascm_jackknife_plus/reference.R``
against augsynth 0.2.0 on the bundled ``kansas`` panel (vendored as
``basedata/kansas_ascm.csv``). Install the reference with
``bash benchmarks/R/install_augsynth.sh``; the gold is committed, so this case
runs without R.
"""
from __future__ import annotations

import os
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

_HERE = Path(__file__).resolve().parents[1]
_GOLD = _HERE / "reference" / "ascm_jackknife_plus"
_DATA = _HERE.parent / "basedata" / "kansas_ascm.csv"

_TREATED_FIPS = 20
_T_INT = 2012.25


def _prep():
    """``(y_pre, Y0_pre, y_post, Y0_post)`` as augsynth sees the Kansas panel."""
    d = pd.read_csv(os.path.abspath(_DATA))
    piv = d.pivot(index="fips", columns="year_qtr",
                  values="lngdpcapita").sort_index()
    times = np.array(sorted(d["year_qtr"].unique()))
    n_pre = int((times < _T_INT).sum())
    Y = piv.to_numpy()
    trt = piv.index.to_numpy() == _TREATED_FIPS
    y, Y0 = Y[trt][0], Y[~trt]
    return y[:n_pre], Y0[:, :n_pre].T, y[n_pre:], Y0[:, n_pre:]


def _gold(name):
    p = _GOLD / name
    return pd.read_csv(p) if p.exists() else None


def run() -> dict:
    from mlsynth.utils.bilevel.jackknife_plus import jackknife_plus

    y_pre, Y0_pre, y_post, Y0_post = _prep()
    out: dict = {}

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        fits = {c: jackknife_plus(y_pre, Y0_pre, y_post, Y0_post, alpha=0.05,
                                  conservative=c)
                for c in (False, True)}

    # Pure-Python invariants, independent of whether the gold is present.
    r = fits[False]
    out["n_drops"] = float(r.held_out_errors.size)
    out["bounds_ordered"] = float(np.all(r.lower <= r.upper))
    out["appended_entry_is_the_mean"] = float(np.allclose(
        r.per_drop_estimates[:, -1], r.per_drop_estimates[:, :-1].mean(axis=1),
        rtol=0, atol=1e-12))
    # NOT "conservative is wider" -- it is not, on this panel, in 16 of 17
    # periods. See the module docstring. What is exactly true is its
    # construction, so that is what gets pinned.
    q = float(np.quantile(np.abs(r.held_out_errors), 0.95, method="linear"))
    est = r.per_drop_estimates
    expected_width = (est.max(axis=0) - est.min(axis=0)) + 2.0 * q
    got_width = fits[True].upper - fits[True].lower
    out["conservative_width_matches_construction"] = float(
        np.max(np.abs(got_width - expected_width)))

    perdrop = _gold("gold_perdrop.csv")
    if perdrop is None:
        for k in ("perdrop_err_max_diff", "perdrop_est_max_diff",
                  "bounds_max_diff", "bounds_max_diff_conservative",
                  "average_att_lower_diff", "average_att_upper_diff"):
            out[k] = float("nan")
        return out

    exp_err = (perdrop.sort_values(["tdrop", "pos"])
               .groupby("tdrop").err.first().to_numpy())
    exp_est = (perdrop.sort_values(["tdrop", "pos"])
               .pivot(index="tdrop", columns="pos", values="est").to_numpy())
    out["perdrop_err_max_diff"] = float(
        np.max(np.abs(r.held_out_errors - exp_err)))
    out["perdrop_est_max_diff"] = float(
        np.max(np.abs(r.per_drop_estimates - exp_est)))

    for cons, key in ((False, "bounds_max_diff"),
                      (True, "bounds_max_diff_conservative")):
        g = _gold(f"gold_jackknife_plus_conservative_{str(cons).lower()}.csv")
        post = g[g.lb.notna()]
        f = fits[cons]
        out[key] = float(max(np.max(np.abs(f.lower - post.lb.to_numpy())),
                             np.max(np.abs(f.upper - post.ub.to_numpy()))))
        if not cons:
            avg = g.iloc[-1]
            out["average_att_lower_diff"] = float(abs(f.lower[-1] - avg.lb))
            out["average_att_upper_diff"] = float(abs(f.upper[-1] - avg.ub))
    return out


#: Agreement is asserted as a distance from augsynth, so every row reads as
#: "how far apart are we" rather than as a value to be re-fitted if it drifts.
EXPECTED = {
    "n_drops": (89.0, 0.5),
    "bounds_ordered": (1.0, 0.5),
    "appended_entry_is_the_mean": (1.0, 0.5),
    "conservative_width_matches_construction": (0.0, 1e-9),
    # QP-solver floor, per the module docstring.
    "perdrop_err_max_diff": (0.0, 1e-6),
    "perdrop_est_max_diff": (0.0, 1e-6),
    "bounds_max_diff": (0.0, 1e-7),
    "bounds_max_diff_conservative": (0.0, 1e-6),
    "average_att_lower_diff": (0.0, 1e-7),
    "average_att_upper_diff": (0.0, 1e-7),
}
