"""Ridge ASCM vs augsynth on Cunningham's two Mixtape studies.

Cross-validation (the reference is the augsynth R package, Ben-Michael, Feller &
Rothstein 2021, pinned at commit ``7a90ea48``). Scott Cunningham's teaching
material runs ``augsynth(y ~ treated, progfunc = "ridge", scm = TRUE)`` on two
panels, and the pair is more informative than either alone because the
augmentation behaves completely differently on them:

    study    treated       T0   J    lambda      what ridge does to the fit
    Prop 99  California    19   38   4.30e+02    pre-fit RMSE 1.656 -> 0.734
    Texas    Texas          8   50   1.74e+10    pre-fit RMSE 862.9 -> 861.3

Prop 99 is the method working as advertised. The simplex fit puts weight on six
donors and still misses California by 1.66 packs per capita; the augmentation
halves that, spreading onto 36 donors with negative weights summing to -0.28 --
the extrapolation outside the convex hull that the ridge correction exists to
allow.

Texas is where it switches itself off, and that is why this case exists. With
only 8 pre-periods the cross-validation cannot justify any augmentation at all:
it selects a penalty of 1.74e+10, the fitted weights move by at most 3.2e-04
from the plain simplex solution, the support stays at the same three donors
(Florida 0.373, New York 0.356, Illinois 0.272), negative weights sum to -0.002,
and the pre-fit improves by 0.2%. ASCM has degenerated to SCM.

It does not do so for want of trying. Texas is the harder problem of the two --
its treated unit sits at the 96th percentile of the donor pool, rank 3 of 51 in
every pre-treatment year, and the simplex fit misses by 20% of the treated
series' own pre-period standard deviation against Proposition 99's 14.6%. Handed
a penalty of 10, the augmentation extrapolates six times harder there than on
Proposition 99: negative weights sum to -4.55 against -0.72. What it cannot do
is make that extrapolation generalise. The best held-out improvement available
over plain SCM across a penalty grid is 0.7% on Texas and 28% on Proposition 99,
so the cross-validation discards the correction on one panel and keeps it on the
other.

Which is why near-zero negative weights are not the diagnostic they look like.
They are equally consistent with a simplex fit so good the correction has
nothing to do, and with an augmentation the cross-validation switched off over a
fit that is poor; the two are told apart by the pre-treatment residual, not by
the weights. Texas is the second, and reading it as the first inverts what the
panel is saying.

The penalty gap is not units. Prison counts run about 19,400 against 116 packs
per capita, so an outcome-scale penalty would differ by roughly 2.8e+04 between
the panels; the selected penalties differ by 4.0e+07, three orders beyond that.
The difference is the short pre-period, not the scale.

The failure this case guards is invisible.
An implementation whose penalty grid was clamped, or whose CV shrank differently
at short T0, would turn the augmentation back on here -- and the pre-treatment
fit would look essentially identical, since ridge only moves it by 0.2%, while
the post-period counterfactual and the ATT would move. Nothing in a plot of the
fit would show it.

Everything is read through the public estimator. Augmented SCM is a mode of
:class:`~mlsynth.estimators.vanillasc.VanillaSC` (``augment="ridge"``) and the
jackknife+ interval is ``inference="jackknife_plus"``, so the case exercises the
path a user calls and reads ``res.effects.att``, ``res.weights.donor_weights``
and ``res.inference`` -- never estimator-private fields. ``ascm_kansas`` covers
the same layer through its helper functions; this covers the estimator around
them.

What is pinned. Both studies pin the average ATT, the pre-treatment L2 imbalance
and its scaled version, the jackknife+ interval on the post-period average, the
selected ridge penalty, how much the augmentation moves the pre-fit, and every
donor weight -- 88 of them across the two panels, so a regression is localised
to a donor and not merely reported as "the ATT moved".

The scaled L2 imbalance is augsynth's ``scaled_l2_imbalance``: the L2 imbalance
over the imbalance uniform donor weights would leave, so it reads as the
fraction of the naive gap left unclosed. Both fits close about 95% of it, which
is the one thing the two studies agree on.

Provenance: gold generated by ``benchmarks/reference/ascm_mixtape/reference.R``
against a live augsynth 0.2.0 run, captured with its session info and input
checksums in ``benchmarks/reference/ascm_mixtape/``. Install the reference with
``bash benchmarks/R/install_augsynth.sh``; the gold is committed, so this case
runs without R. Data: ``basedata/smoking_data.csv`` (the Mixtape's
``synth_smoking.dta`` with state labels decoded -- California is state 3 there
-- agreeing with it to 1.2e-05, which is float32 storage in the ``.dta``) and
``basedata/texas_bmprison.csv`` (the ``bmprison`` columns of the Mixtape's
``texas.dta``, 51 states x 1985-2000, balanced).
"""
from __future__ import annotations

import os
import warnings

import numpy as np
import pandas as pd

from benchmarks.reference import load_reference, reference_value

_BASE = os.path.join(os.path.dirname(__file__), "..", "..", "basedata")

# (file, unit column, outcome column, treated unit, first treated period)
_STUDIES = {
    "prop99": ("smoking_data.csv", "state", "cigsale", "California", 1989),
    "texas": ("texas_bmprison.csv", "statefip", "bmprison", 48, 1993),
}


def study_frame(study: str):
    """The panel with augsynth's treatment indicator added."""
    fname, unit, outcome, treated, t_int = _STUDIES[study]
    d = pd.read_csv(os.path.abspath(os.path.join(_BASE, fname)))
    d["treated"] = ((d[unit] == treated) & (d["year"] >= t_int)).astype(int)
    return d, unit, outcome, treated, t_int


def donor_pre_matrix(study: str):
    """``(y_pre, Y0_pre, donor_labels)`` in donor order, for the imbalance measures."""
    d, unit, outcome, treated, t_int = study_frame(study)
    piv = d.pivot(index=unit, columns="year", values=outcome).sort_index()
    n_pre = int((np.array(sorted(d["year"].unique())) < t_int).sum())
    trt = piv.index.to_numpy() == treated
    if trt.sum() != 1:
        raise ValueError(f"{study}: expected one treated unit, got {int(trt.sum())}")
    Y = piv.to_numpy()
    labels = [str(u) for u in piv.index.to_numpy()[~trt]]
    return Y[trt][0][:n_pre], Y[~trt][:, :n_pre].T, labels


def _l2(w, y_pre, Y0_pre):
    """augsynth's ``l2_imbalance``: the pre-fit gap, donor-mean centred.

    augsynth measures imbalance against the per-period donor average and not
    against zero, so a fit that merely reproduces the donor pool scores as
    completely unbalanced and not as perfectly balanced.
    """
    mu = Y0_pre.mean(1)
    return float(np.sqrt(np.sum(((y_pre - mu) - (Y0_pre - mu[:, None]) @ w) ** 2)))


def _fit(study: str) -> dict:
    import matplotlib
    matplotlib.use("Agg")
    from mlsynth import VanillaSC
    from mlsynth.config_models import VanillaSCConfig

    d, unit, outcome, _, _ = study_frame(study)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = VanillaSC(VanillaSCConfig(
            df=d, outcome=outcome, treat="treated", unitid=unit, time="year",
            augment="ridge", inference="jackknife_plus",
            display_graphs=False)).fit()

    y_pre, Y0_pre, labels = donor_pre_matrix(study)
    w = np.array([res.weights.donor_weights[k] for k in labels])
    J = Y0_pre.shape[1]
    out = {
        f"att_{study}": float(res.effects.att),
        f"l2_{study}": _l2(w, y_pre, Y0_pre),
        f"scaled_l2_{study}": _l2(w, y_pre, Y0_pre) / _l2(np.full(J, 1.0 / J),
                                                          y_pre, Y0_pre),
        f"att_lower_{study}": float(res.inference.details["average_att_lower"]),
        f"att_upper_{study}": float(res.inference.details["average_att_upper"]),
        f"lambda_{study}": float(res.inference.details["lambda"]),
    }
    # The whole weight vector against augsynth's, reduced to its worst cell so
    # one number reports which donor drifted and by how much.
    ref_w = load_reference("ascm_mixtape")["weights"]
    diffs = {lab: abs(res.weights.donor_weights[lab] - ref_w[f"{study}.{lab}"])
             for lab in labels}
    out[f"max_weight_gap_{study}"] = float(max(diffs.values()))
    out[f"n_weights_{study}"] = float(len(labels))

    # How much the augmentation actually changes the fit, against the plain
    # simplex solution it starts from. This is the quantity that separates the
    # two studies, and the one a clamped penalty grid would move while leaving
    # the pre-fit picture unchanged.
    from mlsynth.utils.bilevel.minnorm import simplex_gram, solve_simplex_minnorm
    w_scm = solve_simplex_minnorm(simplex_gram(Y0_pre, y_pre))
    r_scm = float(np.linalg.norm(Y0_pre @ w_scm - y_pre))
    r_ridge = float(np.linalg.norm(Y0_pre @ w - y_pre))
    out[f"ridge_rmse_gain_{study}"] = 1.0 - r_ridge / r_scm
    out[f"ridge_weight_shift_{study}"] = float(np.abs(w - w_scm).max())
    return out


# Penalty grid for the out-of-sample probe, and a probe penalty far below
# either study's cross-validated pick, used to ask what the augmentation would
# do if it were allowed to.
_LOO_GRID = (1e0, 1e2, 1e4, 1e6, 1e8, 1e10, 1e12)
_PROBE_LAMBDA = 10.0
_NO_AUGMENTATION = 1e18          # ridge shrunk to nothing, i.e. plain SCM


def _loo_rmse(y, Y0, lam):
    """Held-out pre-period RMSE: drop each pre-period, refit at ``lam``, predict it.

    The penalty is forced, so this measures the augmentation itself and not the
    package's choice of penalty.
    """
    from mlsynth.utils.bilevel.ridge_augment import ridge_augment_weights
    T0 = len(y)
    errs = []
    for t in range(T0):
        keep = np.arange(T0) != t
        w = ridge_augment_weights(y[keep], Y0[keep], lambda_=lam).W
        errs.append(y[t] - Y0[t] @ w)
    return float(np.sqrt(np.mean(np.square(errs))))


def _extrapolation_probe(study: str) -> dict:
    """What the augmentation would do, and whether it would generalise.

    Two questions the fitted numbers cannot answer on their own, because the
    cross-validated penalty has already resolved them. First: how much
    out-of-sample accuracy is available from augmenting at all --
    ``loo_best_gain``, the largest held-out improvement over plain SCM across a
    fixed penalty grid. Second: how hard the augmentation would extrapolate if
    the penalty let it -- ``sum_neg_probe``, the total negative weight at a
    penalty far below either study's pick.

    The pair separates want from worth. Texas wants to extrapolate six times
    harder than Proposition 99 does -- its treated unit sits at the 96th
    percentile of the donor pool and no convex combination reaches it -- and
    gets essentially nothing for it out of sample, so the cross-validation
    discards the correction. Proposition 99 wants less and gains far more, so
    the correction survives. That is the mechanism behind the penalty gap the
    case pins above, and it is what a reader of the fitted weights alone would
    have to guess at: near-zero negative weights are equally consistent with a
    perfect simplex fit and with an augmentation that was switched off, and only
    the second is true here.
    """
    from mlsynth.utils.bilevel.ridge_augment import ridge_augment_weights

    y, Y0, _ = donor_pre_matrix(study)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        scm = _loo_rmse(y, Y0, _NO_AUGMENTATION)
        best = min(_loo_rmse(y, Y0, lam) for lam in _LOO_GRID)
        w_probe = ridge_augment_weights(y, Y0, lambda_=_PROBE_LAMBDA).W
        w_cv = ridge_augment_weights(y, Y0).W
        w_scm = ridge_augment_weights(y, Y0, lambda_=_NO_AUGMENTATION).W
    return {
        f"loo_best_gain_{study}": 1.0 - best / scm,
        f"sum_neg_probe_{study}": float(w_probe[w_probe < 0].sum()),
        f"sum_neg_cv_{study}": float(w_cv[w_cv < 0].sum()),
        # The base fit is a genuine simplex solution: no negative weights at all.
        # augsynth's own plain SCM returns 46 of them here at -4e-09, which is
        # osqp's solve tolerance and not a feature of the program.
        f"scm_base_negatives_{study}": float((w_scm < -1e-9).sum()),
    }


def run() -> dict:
    out = {}
    for study in _STUDIES:
        out.update(_fit(study))
        out.update(_extrapolation_probe(study))
    # The same estimator meeting opposite problems: the penalty the CV selects
    # differs by seven orders of magnitude, because the Texas simplex fit
    # already interpolates and there is nothing left to penalise. Pinned as an
    # ordering, so it guards the behaviour without pinning a grid ceiling a
    # future CV range could legitimately move.
    out["texas_penalty_runs_away"] = float(
        out["lambda_texas"] > 1e6 * out["lambda_prop99"])
    return out


def comparison() -> dict:
    """mlsynth's ridge ASCM against augsynth, cell by cell, for both studies."""
    got = run()
    rows = []
    for study, label in (("prop99", "Prop 99"), ("texas", "Texas")):
        for key, name in (("att", "ATT"), ("l2", "pre_fit_L2"),
                          ("scaled_l2", "scaled_L2"),
                          ("att_lower", "jackknife+ lower"),
                          ("att_upper", "jackknife+ upper")):
            rows.append({
                "quantity": f"{name}[{label}]",
                "mlsynth": round(got[f"{key}_{study}"], 6),
                "reference": round(reference_value("ascm_mixtape",
                                                   f"{key}_{study}"), 6),
            })
    return {
        "rows": rows,
        "mlsynth_call": {
            "estimator": "VanillaSC",
            "augment": "ridge", "inference": "jackknife_plus",
        },
        "reference": {
            "impl": "augsynth 0.2.0 (R, commit 7a90ea48)",
            "call": 'augsynth(y ~ treated, unit, time, progfunc = "ridge", scm = TRUE)',
        },
    }


def _ref(key: str) -> float:
    return reference_value("ascm_mixtape", key)


# Tolerances are a fixed fraction of each quantity's own scale -- 5e-06 relative
# on the ATT and interval bounds, 1e-05 relative on the imbalance measures --
# because cigarette packs per capita and prisoner counts differ by three orders
# of magnitude and one absolute number cannot be honest about both. Measured
# agreement is 6.3e-07 relative (Prop 99 ATT) and 4.1e-07 (Texas ATT), so each
# tolerance sits about an order of magnitude above the observed difference:
# tight enough that a real change in the fit fails, loose enough to absorb osqp
# against mlsynth's exact active set on a different BLAS. Two exact solvers
# agree to their own tolerances, not bit-for-bit, and that is the floor.
#
# This only works because the reference prints significant digits. At the %.6f
# the script first used, ``scaled_l2_prop99`` = 0.045728 carried five
# significant digits, so its own rounding was 5e-07 against a 4.6e-07 tolerance
# and the cell failed on the format and not on the fit. The reference prints
# %.12g now, which keeps precision uniform across quantities whatever their
# magnitude.
def _tol(value: float, rel: float) -> float:
    return max(abs(value) * rel, 1e-09)


