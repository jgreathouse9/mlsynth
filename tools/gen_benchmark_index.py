#!/usr/bin/env python3
"""Regenerate the complete benchmark index in ``docs/benchmarks.rst``.

The curated sections below the index are prose: a maintainer writes a sentence
about a case when it is interesting, and 61 cases had never got one. That is
fine for prose and useless as a roster, so the roster is generated from
:data:`benchmarks.registry.LABELS` instead and checked in CI.

    python tools/gen_benchmark_index.py            # rewrite the block
    python tools/gen_benchmark_index.py --check    # exit 1 if it is stale

The block is delimited by the two markers below; everything between them is
overwritten, and everything outside is left alone.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

DOCS = ROOT / "docs" / "benchmarks.rst"
START = ".. BENCHMARK-INDEX-START (generated by tools/gen_benchmark_index.py)"
END = ".. BENCHMARK-INDEX-END"


def render() -> str:
    from benchmarks import registry as reg

    counts = {p: len(reg.by_path(p)) for p in reg.PATH_NAMES}
    kinds = {k: len(reg.by_data(k)) for k in reg.DATA_KINDS}
    touch_sim = kinds["simulated"] + kinds["both"]

    out = [START, ""]
    out += [
        "Every case, by path and data",
        "-" * 28,
        "",
        f"All {len(reg.LABELS)} registered cases. ``paths`` is what the case",
        "establishes and ``data`` is what it runs on; the two are independent, so",
        "a cross-validation can sit on a generated panel and a simulation can be",
        "calibrated from a real one.",
        "",
    ]
    for letter, description in reg.PATH_NAMES.items():
        out.append(f"* ``{letter}`` -- {description} ({counts[letter]} cases)")
    out += [
        "",
        f"By data: {kinds['simulated']} simulated, {kinds['empirical']} empirical, "
        f"{kinds['both']} both -- so {touch_sim} cases fit at least one generated panel.",
        "",
        "This table is generated. To change a label, edit ``LABELS`` in",
        "``benchmarks/registry.py`` and run ``python tools/gen_benchmark_index.py``;",
        "``benchmarks/tests/test_registry_labels.py`` fails if the two disagree.",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 40 14 14",
        "",
        "   * - case",
        "     - paths",
        "     - data",
    ]
    for name in sorted(reg.LABELS):
        label = reg.LABELS[name]
        out.append(f"   * - ``{name}``")
        out.append(f"     - {' '.join(sorted(label.paths))}")
        out.append(f"     - {label.data}")
    out += ["", END]
    return "\n".join(out)


def splice(text: str, block: str) -> str:
    if START in text and END in text:
        head = text[: text.index(START)]
        tail = text[text.index(END) + len(END):]
        return head + block + tail
    # first run: insert before the first validation-path section
    anchor = "Path A "
    i = text.index(anchor)
    # back up to the blank line before that heading
    i = text.rindex("\n\n", 0, i) + 2
    return text[:i] + block + "\n\n" + text[i:]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed block is stale")
    args = ap.parse_args()

    current = DOCS.read_text()
    updated = splice(current, render())
    if args.check:
        if current != updated:
            print("docs/benchmarks.rst's generated index is out of date.")
            print("Run: python tools/gen_benchmark_index.py")
            return 1
        print("index is current")
        return 0
    DOCS.write_text(updated)
    print(f"wrote the index block into {DOCS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
