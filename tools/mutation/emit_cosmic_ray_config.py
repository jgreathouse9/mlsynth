"""Emit a ``[cosmic-ray]`` config per target from ``targets.toml``.

    python tools/mutation/emit_cosmic_ray_config.py --out build/cosmic-ray

``module-path``, ``test-command`` and ``timeout`` are cosmic-ray's own keys, so
the targets declared for the semantic catalogue describe a cosmic-ray session
without restating anything. Once cosmic-ray is installable again the workflow
is::

    python tools/mutation/emit_cosmic_ray_config.py --out build/cosmic-ray
    cosmic-ray init build/cosmic-ray/<target>.toml <target>.sqlite
    cosmic-ray exec <target>.toml <target>.sqlite
    cr-report <target>.sqlite

cosmic-ray is currently blocked upstream: its ``yattag`` dependency ships a
legacy ``setup.py`` that modern setuptools rejects (``install_layout`` was
removed), so the wheel cannot be built. The configs are emitted and validated
regardless, which keeps the two halves in step and means the blocker costs a
`pip install` and not a design.

The two instruments answer different questions and neither replaces the other.
cosmic-ray applies general operators over the parso syntax tree, exhaustively
and without imagination -- it asks whether any assertion in a module is weak.
``run_mutants.py`` applies a short catalogue of specific defects a reviewer
thought plausible, several of which are not expressible as a local syntactic
rule at all. See ``targets.toml`` for what belongs in which.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import List

from run_mutants import Target, load_targets

_TEMPLATE = """\
# Generated by tools/mutation/emit_cosmic_ray_config.py -- do not edit.
# Source of truth: tools/mutation/targets.toml

[cosmic-ray]
module-path = "{module_path}"
timeout = {timeout}
excluded-modules = []
test-command = "{test_command}"

[cosmic-ray.distributor]
name = "local"
"""


def render(target: Target) -> str:
    return _TEMPLATE.format(
        module_path=target.module_path.as_posix(),
        timeout=target.timeout,
        test_command=target.test_command.replace('"', '\\"'),
    )


def main(argv: List[str] | None = None) -> int:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--targets-file", default=str(here / "targets.toml"))
    parser.add_argument("--out", default="build/cosmic-ray",
                        help="directory to write the per-target configs into")
    args = parser.parse_args(argv)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for target in load_targets(Path(args.targets_file)):
        path = out / f"{target.name}.toml"
        path.write_text(render(target))
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
