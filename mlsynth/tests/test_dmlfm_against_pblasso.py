"""Step-level agreement between the DMLFM port and pblasso 1.0.8.

Every conditional draw in ``src/blasso.cpp`` factors into a deterministic mean
and covariance plus a normal draw. The RNG streams cannot be matched across
languages, but the deterministic halves can, exactly. These tests pin them
against fixtures generated by calling the reference's own Rcpp functions, so a
divergence names the step that is wrong instead of leaving an end-to-end number
to guess at.

Regenerate the fixtures with the script recorded in
``benchmarks/reference/dmlfm_germany/README.md``; it needs pblasso 1.0.8 from
the authors' replication package.
"""

from __future__ import annotations

import json
import pathlib

import numpy as np
import pytest

from mlsynth.utils.dmlfm_helpers.sampler import _group_moments, _tilde, _tilde_tau
from mlsynth.utils.dmlfm_helpers.setup import _starts

FIX = pathlib.Path(__file__).parent / "fixtures" / "dmlfm" / "sampler_steps.json"
TOL = 1e-10


@pytest.fixture(scope="module")
def fx():
    if not FIX.exists():  # pragma: no cover - fixture is committed
        pytest.skip("pblasso fixtures not generated")
    return json.loads(FIX.read_text())


def arr(x):
    return np.asarray(x, float)


def test_group_starts_match_breakID(fx):
    id0 = arr(fx["inputs"]["id0"]).astype(int) - 1
    assert np.array_equal(_starts(id0), arr(fx["breakID_id"]).astype(int))


def test_group_moments_match_genXY(fx):
    inp = fx["inputs"]
    X, y = arr(inp["X"]), arr(inp["y"]).reshape(-1, 1)
    starts = _starts(arr(inp["id0"]).astype(int) - 1)
    assert np.allclose(_group_moments(X, y, starts), arr(fx["genXY"]), atol=TOL)
    assert np.allclose(_group_moments(X, X, starts), arr(fx["genXX"]), atol=TOL)


def test_beta_posterior_covariance_and_mean(fx):
    """sampleN's deterministic core, including the flat prior on coefficient 0."""
    inp = fx["inputs"]
    X, y, s2 = arr(inp["X"]), arr(inp["y"]), float(inp["sigma2"])
    k = X.shape[1]
    prec0 = np.zeros((k, k))
    for j in range(1, k):
        prec0[j, j] = 1.0 / 100.0
    S = np.linalg.inv(X.T @ X / s2 + prec0)
    mu = S @ (X.T @ y / s2)
    assert np.allclose(S, arr(fx["genCov1"]), atol=TOL)
    assert np.allclose(mu, arr(fx["genMu"]).ravel(), atol=TOL)


def test_tilde_expansion_with_and_without_a_block(fx):
    inp = fx["inputs"]
    X, F = arr(inp["X"]), arr(inp["F"])
    om = arr(inp["omega"])
    tcode = arr(inp["time"]).astype(int) - 1
    k, r = int(inp["k"]), int(inp["r"])
    assert np.allclose(_tilde(X, F, om, tcode), arr(fx["genTildeZ_full"]), atol=TOL)
    empty = np.zeros((X.shape[0], 0))
    assert np.allclose(_tilde(empty, F, om[k:k + r], tcode),
                       arr(fx["genTildeZ_bare"]), atol=TOL)


def test_tilde_tau_matches(fx):
    inp = fx["inputs"]
