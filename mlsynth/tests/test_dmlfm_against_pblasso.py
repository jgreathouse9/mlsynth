def test_partial_fits_match(fx):
    inp = fx["inputs"]
    X = arr(inp["X"])
    ucode = arr(inp["id0"]).astype(int) - 1
    tcode = arr(inp["time"]).astype(int) - 1
    re_fit = np.einsum("ij,ij->i", X, arr(inp["Alpha"])[ucode])
    assert np.allclose(re_fit, arr(fx["getREfit"]), atol=TOL)
    ffit = np.einsum("ij,ij->i", arr(inp["Gamma"])[ucode], arr(inp["F"])[tcode])
    assert np.allclose(ffit, arr(fx["getFactorFit"]), atol=TOL)


def test_phi_posterior_moments_match(fx):
    """samplePhi's varphi and muphi (blasso.cpp:739-740)."""
    Xi = arr(fx["inputs"]["Xi"])
    lag = np.vstack([np.zeros((1, Xi.shape[1])), Xi[:-1]])
    xx, xy = lag.T @ lag, lag.T @ Xi
    assert np.allclose(xx, arr(fx["phi_xx"]), atol=TOL)
    assert np.allclose(xy, arr(fx["phi_xy"]), atol=TOL)
    k = Xi.shape[1]
    var = np.array([1.0 / (xx[i, i] + 1.0 / 100.0) for i in range(k)])
    mu = np.array([var[i] * xy[i, i] for i in range(k)])
    assert np.allclose(var, arr(fx["phi_var"]), atol=TOL)
    assert np.allclose(mu, arr(fx["phi_mu"]), atol=TOL)


