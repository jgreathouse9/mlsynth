def test_loading_step_posterior_moments(fx2):
    """iterGenAlpha (blasso.cpp:367): per-unit A1 and bara."""
    from mlsynth.utils.dmlfm_helpers.sampler import _group_moments
    tZ, res = arr(fx2["tZ"]), arr(fx2["res"]).reshape(-1, 1)
    s2 = float(fx2["sigma2"])
    kk = tZ.shape[1]
    starts = _starts(arr(fx2["id0"]).astype(int) - 1)
    XX = _group_moments(tZ, tZ, starts)
    XY = _group_moments(tZ, res, starts)
    inv0 = np.linalg.inv(np.eye(kk))
    for i in range(int(fx2["N"])):
        A1 = np.linalg.inv(XX[i * kk:(i + 1) * kk] / s2 + inv0)
        mu = A1 @ XY[i * kk:(i + 1) * kk].ravel() / s2
        assert np.allclose(A1, arr(fx2["A1"][i]), atol=TOL), f"A1 unit {i}"
        assert np.allclose(mu, arr(fx2["bara"][i]).ravel(), atol=TOL), f"bara unit {i}"


def test_time_state_step_posterior_moments(fx2):
    """iterGenXi (blasso.cpp:619): per-period precision and mean, including the
    first period conditioning on its forward neighbour only."""
    from mlsynth.utils.dmlfm_helpers.sampler import _group_moments
    tA, res = arr(fx2["tA"]), arr(fx2["res"]).reshape(-1, 1)
    s2 = float(fx2["sigma2"])
    ucode = arr(fx2["id0"]).astype(int) - 1
    tcode = arr(fx2["time"]).astype(int) - 1
    order = np.lexsort((ucode, tcode))
    kk, TT = tA.shape[1], int(fx2["TT"])
    starts = _starts(tcode[order])
    XX = _group_moments(tA[order], tA[order], starts)
    XY = _group_moments(tA[order], res[order], starts)
    phi = arr(fx2["Phi"])
    tau_old = arr(fx2["TauOld"])
    I, mphi = np.eye(kk), np.diag(phi)
    pp = mphi @ mphi
    for t in range(TT):
        xx = XX[t * kk:(t + 1) * kk]
        xy = XY[t * kk:(t + 1) * kk].ravel()
        if t < TT - 1:
            prec = I + xx / s2 + pp
            mu = xy / s2 + (mphi @ tau_old[1] if t == 0
                            else mphi @ (tau_old[t - 1] + tau_old[t + 1]))
        else:
            prec = I + xx / s2
            mu = xy / s2 + mphi @ tau_old[t - 1]
        assert np.allclose(prec, arr(fx2["prec"][t]), atol=TOL), f"precision t={t}"
        assert np.allclose(np.linalg.inv(prec) @ mu, arr(fx2["mu"][t]).ravel(),
                           atol=TOL), f"mean t={t}"


